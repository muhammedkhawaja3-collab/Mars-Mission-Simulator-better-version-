/**
 * Regenerates shared/golden_cases.json from the JS physics engine.
 *
 *   npm run golden
 *
 * The output is deterministic (no dates, no randomness beyond seeded RNG),
 * so re-running it without engine changes gives no git diff. The Vitest test
 * src/physics/__tests__/golden.test.js and the Python mirror both check
 * that they reproduce these results (relative tolerance 1e-9).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { simulateMission, MISSION_SCHEMA_VERSION } from '../src/physics/index.js';
import { GOLDEN_CASES, toSimulateArgs } from './golden-cases.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../shared/golden_cases.json');

const doc = {
  description: 'Golden fixtures for the Mars mission physics engine. Generated by frontend/scripts/gen-golden.mjs; do not edit by hand.',
  schemaVersion: MISSION_SCHEMA_VERSION,
  tolerance: { relative: 1e-9, absolute: 1e-12 },
  cases: GOLDEN_CASES.map(({ id, description, input }) => ({
    id,
    description,
    input,
    expected: simulateMission(toSimulateArgs(input)),
  })),
};

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`Wrote ${doc.cases.length} golden cases to shared/golden_cases.json`);
